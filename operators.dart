void main(){
  int a=5;
  int b=7;
  
  //Arithmetic operators
  print("arithmetic operators");
  print(a+b);
  print(a-b);
  print(a*b);
  print(a%b);
  //Assignment operators
  print("Assignment operators");
  print(a==b);
  print(a!=b);
  print(a<b);
  print(a>b);
  print(a<=b);
  print(a>=b);
  //logical operators
  print("logical operators");
  print(a&b);
  print(a|b);
}
  
  